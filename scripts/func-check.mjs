import puppeteer from 'puppeteer-core';
const URL = process.argv[2] || 'https://mhccog.github.io/heirloom-atlas/';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] });
const p = await b.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.setViewport({ width: 1280, height: 860 });
const w = ms => new Promise(r => setTimeout(r, ms));
await p.goto(URL, { waitUntil: 'networkidle0' }); await p.waitForFunction('window.__ready');
await p.click('#btn-add'); await w(200);
await p.type('dialog [name=name]', 'Test Silver Co'); await p.select('dialog [name=town]', 'lewes'); await p.type('dialog [name=need]', 'Buyers for silver');
await p.click('dialog button[value=ok]'); await w(800);
const card = await p.$eval('#sheet-body h2', e => e.textContent);
await p.evaluate(() => document.querySelector('#sheet-close').click());
await p.click('[data-tab=intros]'); await w(200); await p.click('#add-intro'); await w(200);
const ids = await p.$$eval('dialog [name=a] option', o => o.map(x => x.value));
await p.select('dialog [name=a]', ids.find(i => i.startsWith('walkin-'))); await p.select('dialog [name=b]', 'gorringe-s'); await p.type('dialog [name=why]', 'Silver from estates');
await p.click('dialog button[value=ok]'); await w(500);
const mine = await p.$$eval('#intro-list .intro', a => a.length);
const client = await p.createCDPSession(); await client.send('Browser.setDownloadBehavior', { behavior: 'allow', downloadPath: '/tmp/ha-dl' }).catch(()=>{});
await client.send('Page.setDownloadBehavior', { behavior: 'allow', downloadPath: '/tmp/ha-dl' }).catch(()=>{});
await p.click('#btn-data'); await w(200); await p.click('#d-json'); await w(600); await p.click('#d-csv'); await w(800);
await p.keyboard.press('Escape');
await p.click('[data-tab=people]'); await w(300); await p.type('#q', 'silver'); await w(300);
await p.click('.seg [data-layout=list]'); await w(300);
const listN = await p.$$eval('#list .pcard', a => a.length);
const st = await p.evaluate(() => { const s = JSON.parse(localStorage.getItem('heirloom-atlas/v1')); return { myBiz: s.myBiz.length, myIntros: s.myIntros.length }; });
await p.evaluate(() => localStorage.removeItem('heirloom-atlas/v1'));
const fs = await import('fs'); const files = fs.existsSync('/tmp/ha-dl') ? fs.readdirSync('/tmp/ha-dl') : [];
console.log(JSON.stringify({ card, mineIntrosShown: mine, listMatchesSilver: listN, st, downloads: files, errs }));
await b.close();
